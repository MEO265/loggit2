test_that("disabling locking bypasses every log operation and can be reversed", {
  old <- set_safe_multi_process(FALSE, confirm = FALSE)
  old_logfile <- get_logfile()
  path <- tempfile()
  lock_path <- paste0(path, ".lock")
  on.exit({
    set_safe_multi_process(old, confirm = FALSE)
    set_logfile(old_logfile, confirm = FALSE, create = FALSE)
    unlink(c(path, lock_path), recursive = TRUE)
  }, add = TRUE)
  # A directory cannot be opened as a lock file, so any lock attempt would fail.
  dir.create(lock_path)
  set_logfile(path, confirm = FALSE)
  loggit("INFO", "first", logfile = path, echo = FALSE)
  expect_identical(read_logs(path)$log_msg, "first")
  rotate_logs(0L, path)
  suppressMessages(with_loggit({
    base::message("second")
    rotate_logs(0L, path)
    base::message("third")
  }, logfile = path, echo = FALSE))
  expect_identical(read_logs(path)$log_msg, "third\n")
  unlink(lock_path, recursive = TRUE)
  rotate_logs(1L, path)
  expect_false(file.exists(lock_path))
  set_safe_multi_process(TRUE, confirm = FALSE)
  loggit("INFO", "locked again", logfile = path, echo = FALSE)
  expect_true(file.exists(lock_path))
  set_safe_multi_process(FALSE, confirm = FALSE)
  rotate_logs(0L, path)
  expect_true(file.exists(lock_path))
})
